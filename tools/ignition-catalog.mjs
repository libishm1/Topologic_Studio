/**
 * Compiles the ignition-source review's catalogue
 * (wiki/research/ignition-sources-2026-11-05.json) into the module the app
 * imports, src/core/ignitionCatalog.js: per scenario, the IFC entities and
 * predefined types that identify it, its name and room patterns, its share of
 * fire deaths (the ranking weight) and its design fire, with the source keys.
 *
 *   node tools/ignition-catalog.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REVIEW = path.join(HERE, "../wiki/research/ignition-sources-2026-11-05.json");
const OUT = path.join(HERE, "../topologicpy-web-frontend/src/core/ignitionCatalog.js");

const review = JSON.parse(await readFile(REVIEW, "utf8"));
const value = (x) => (x && typeof x === "object" ? x.value ?? null : x ?? null);
const source = (x) => (x && typeof x === "object" ? x.source ?? null : null);

const scenarios = review.scenarios.map((s) => ({
  id: s.id,
  label: s.label,
  fireClass: s.fireClass,
  fuelClass: s.fuelClass ?? null,
  room: s.room ?? null,
  entities: (s.ifc || [])
    .filter((e) => e.entity)
    .map((e) => ({
      entity: e.entity.toUpperCase(),
      predefinedType: e.predefinedType ?? null,
      byName: Boolean(e.byName),
      weight: e.weight ?? 1,
    })),
  nameRegex: s.nameRegex ?? null,
  nameExclude: s.nameExclude ?? null,
  spaceRegex: s.spaceRegex ?? null,
  deathShare: value(s.shareDeaths),
  deathShareOf: s.shareDeaths?.of ?? null,
  nonResidentialShare: value(s.shareNonResidential),
  fireShare: value(s.share),
  fireShareOf: s.share?.of ?? null,
  designFire: s.designFire ? { growth: s.designFire.growth ?? null, alpha: s.designFire.alpha_kW_per_s2 ?? null, peakKw: s.designFire.peak_kW ?? null } : null,
  sources: [...new Set([source(s.shareDeaths), source(s.share), source(s.shareNonResidential), ...(s.designFire?.source ? [].concat(s.designFire.source) : [])].flat().filter(Boolean))],
  evidence: s.evidence ?? null,
}));

const header = `/**
 * Ignition scenarios for "Likely ignition points" (src/core/ignition.js),
 * generated by tools/ignition-catalog.mjs from the review
 * wiki/research/ignition-sources-2026-11-05.json (${review.date}); edit the review and
 * regenerate rather than editing this file. Source keys resolve in the
 * review's "sources" (every DOI checked at Crossref). Ranking rule, from the
 * review: score = deathShare x match confidence / candidates of that scenario.
 */
`;
await writeFile(OUT, `${header}export const RANKING = ${JSON.stringify(review.ranking, null, 2)};\n\nexport const IGNITION_SCENARIOS = ${JSON.stringify(scenarios, null, 2)};\n`);
console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${scenarios.length} scenarios`);
